-- registry_instance_*: SQLite keeps the two instance-id columns equal with AFTER triggers that update their
-- own table (safe there because recursive_triggers is off). Here BEFORE row triggers set NEW instead, so
-- no trigger fires another. Same names, same end state. BEFORE triggers fire in name order, so
-- registry_instance_update_new runs before registry_instance_update_previous, as the SQLite pair settles.
-- +goose StatementBegin
CREATE FUNCTION registry_instance_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.tether_instance_id := COALESCE(NEW.tether_instance_id, NEW.mux_instance_id);
    NEW.mux_instance_id := NEW.tether_instance_id;
    RETURN NEW;
END $$;
-- +goose StatementEnd

CREATE TRIGGER registry_instance_insert BEFORE INSERT ON registry_entries
FOR EACH ROW EXECUTE FUNCTION registry_instance_insert_fn();

-- +goose StatementBegin
CREATE FUNCTION registry_instance_update_new_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.mux_instance_id := NEW.tether_instance_id;
    RETURN NEW;
END $$;
-- +goose StatementEnd

CREATE TRIGGER registry_instance_update_new
BEFORE UPDATE OF tether_instance_id ON registry_entries
FOR EACH ROW WHEN (NEW.tether_instance_id IS NOT NULL AND NEW.tether_instance_id <> NEW.mux_instance_id)
EXECUTE FUNCTION registry_instance_update_new_fn();

-- +goose StatementBegin
CREATE FUNCTION registry_instance_update_previous_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.tether_instance_id := NEW.mux_instance_id;
    RETURN NEW;
END $$;
-- +goose StatementEnd

CREATE TRIGGER registry_instance_update_previous
BEFORE UPDATE OF mux_instance_id ON registry_entries
FOR EACH ROW WHEN (NEW.tether_instance_id IS NULL OR NEW.tether_instance_id <> NEW.mux_instance_id)
EXECUTE FUNCTION registry_instance_update_previous_fn();

