-- The authority check a replacement session's credential must pass. Port notes against the SQLite body:
-- json_extract becomes tether_jx (JSON null reads as SQL NULL, as json_extract returns it), the nested
-- json_extract over props_json.team_definition becomes tether_reparse (it accepts an object or a string
-- holding JSON, as the nested call does), json_each becomes tether_each, julianday becomes tether_ts, and
-- CAST(blob AS TEXT)=json_quote(x) becomes convert_from(blob)=to_json(x)::text. The Go copy in
-- team_recovery_eligibility.go must stay identical in meaning (S2).
-- +goose StatementBegin
CREATE FUNCTION replacement_principal_authority_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM session_replacements WHERE replacement_session_id = NEW.session_id) THEN
        RETURN NEW;
    END IF;
    IF EXISTS (SELECT 1 FROM session_replacements WHERE replacement_session_id = NEW.session_id AND credential_mode = 'off') THEN
        RAISE EXCEPTION 'replacement identity remains off';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM session_replacements x
        JOIN runtime_bindings b ON b.id = x.binding_id AND b.target_urn = x.actor_uri AND b.generation = x.binding_generation
        JOIN team_host_intents h ON h.intent_key = x.intent_key
        JOIN team_port_intents p ON p.port_kind = 'session' AND p.intent_key = h.intent_key
        JOIN team_port_intents e ON e.port_kind = 'enrollment' AND e.intent_key = h.intent_key
        JOIN registry_entries profile ON profile.urn = b.target_urn
        JOIN team_rosters r ON r.run_id = COALESCE(
            NULLIF(tether_jx(tether_json(h.request), '{RunID}') #>> '{}', ''),
            (SELECT tether_jx(tether_json(l.payload), '{Run,id}') #>> '{}'
             FROM team_host_launch_intents i JOIN team_launches l USING (launch_key) WHERE i.intent_key = h.intent_key))
        JOIN team_runs t ON t.run_id = r.run_id
        WHERE x.replacement_session_id = NEW.session_id
          AND b.session_id = NEW.session_id AND b.host_id = 'team' AND b.visibility = 'tether-hosted' AND b.revoked_at IS NULL
          AND (b.lease_expires_at IS NULL OR tether_ts(b.lease_expires_at) > tether_ts('now'))
          AND b.generation = (SELECT MAX(generation) FROM runtime_bindings WHERE target_urn = b.target_urn)
          AND h.tombstone = '' AND h.cleaned = 0 AND h.dead = 0
          AND p.state = 'done' AND p.ended = '' AND convert_from(p.payload, 'UTF8') = to_json(NEW.session_id)::text
          AND e.state = 'done' AND e.ended = '' AND e.binding_ended = 0 AND e.binding_secret = b.attempt_id AND e.acquired_urn = b.target_urn
          AND profile.status = 'active' AND profile.kind = 'agent'
          AND tether_jx(tether_json(e.payload), '{Enrollment,actor}') #>> '{}' = b.target_urn
          AND tether_jx(tether_json(e.payload), '{Enrollment,agent_id}') #>> '{}' = b.target_urn
          AND tether_jx(tether_reparse(tether_jx(tether_json(profile.props_json), '{team_definition}')), '{id}')
              = tether_jx(tether_json(e.payload), '{Pin,id}')
          AND tether_jx(tether_reparse(tether_jx(tether_json(profile.props_json), '{team_definition}')), '{revision}')
              = tether_jx(tether_json(e.payload), '{Pin,revision}')
          AND COALESCE(tether_jx(tether_reparse(tether_jx(tether_json(profile.props_json), '{team_definition}')), '{digest}') #>> '{}', '')
              = COALESCE(tether_jx(tether_json(e.payload), '{Pin,digest}') #>> '{}', '')
          AND tether_jx(tether_json(h.member), '{session_id}') #>> '{}' = NEW.session_id
          AND tether_jx(tether_json(h.member), '{actor}') #>> '{}' = b.target_urn
          AND tether_jx(tether_json(h.member), '{status}') #>> '{}' = 'active'
          AND tether_jx(tether_json(h.member), '{enrolled}') IN ('true'::jsonb, '1'::jsonb)
          AND tether_jx(tether_json(t.payload), '{status}') #>> '{}' NOT IN ('completed', 'failed', 'canceled', 'rejected')
          AND EXISTS (SELECT 1 FROM tether_each(tether_jx(tether_json(r.payload), '{members}')) m
                      WHERE tether_jx(m, '{session_id}') #>> '{}' = NEW.session_id
                        AND tether_jx(m, '{actor}') #>> '{}' = b.target_urn
                        AND tether_jx(m, '{status}') #>> '{}' = 'active')
    ) THEN
        RAISE EXCEPTION 'replacement retained authority unavailable';
    END IF;
    IF EXISTS (
        SELECT 1 FROM session_replacements x WHERE x.replacement_session_id = NEW.session_id
          AND (jsonb_typeof(NEW.scopes_json::jsonb) <> 'array'
            OR (NOT EXISTS (SELECT 1 FROM tether_each(x.credential_scopes_json::jsonb) c WHERE c = '"*"'::jsonb)
                AND EXISTS (SELECT 1 FROM tether_each(NEW.scopes_json::jsonb) n
                            WHERE NOT EXISTS (SELECT 1 FROM tether_each(x.credential_scopes_json::jsonb) ceiling WHERE ceiling = n)))
            OR (x.credential_expires_at IS NOT NULL
                AND (NEW.expires_at IS NULL
                     OR tether_ts(NEW.expires_at) > tether_ts(x.credential_expires_at)
                     OR tether_ts(x.credential_expires_at) <= tether_ts('now'))))
    ) THEN
        RAISE EXCEPTION 'replacement execution credential exceeds inherited ceiling';
    END IF;
    RETURN NEW;
END $$;
-- +goose StatementEnd

