-- Tether's squashed schema for Postgres: the same tables, columns, keys and indexes as
-- migrations/sqlite/00001_schema.sql (the old store at its migration 0101), proven equivalent by
-- TestPostgresSchemaMatchesSQLite in internal/migrate. Hand-maintained: later changes are new migrations
-- (00002 onwards) in both dialect directories, never edits here. One-way: there is no Down.
--
-- Type and construct rules (decisions recorded in docs/conversion-notes.md):
--   INTEGER -> BIGINT; REAL -> DOUBLE PRECISION; BLOB -> BYTEA; TEXT, DATETIME, TIMESTAMP -> TEXT COLLATE "C"
--     (timestamps stay text in the same format, compared bytewise as SQLite's BINARY collation does);
--   INTEGER PRIMARY KEY (with or without AUTOINCREMENT) -> BIGINT GENERATED BY DEFAULT AS IDENTITY;
--   no FOREIGN KEY constraints: SQLite declares them but never enforces them (foreign_keys is off);
--   json_valid -> pg_input_is_valid(x, 'jsonb'); length(CAST(x AS BLOB)) -> octet_length(x); GLOB -> ~;
--   UNIQUE COLLATE NOCASE -> a unique index on lower(); FTS5 -> a tsvector column with a GIN index;
--   each trigger -> a plpgsql function with the same trigger name and the same error text.
-- The seven messaging_* tables are go-messaging's; it has no Postgres store yet (plan section 13.6).

-- +goose Up

-- Helpers for the SQLite constructs the schema uses (see the dialect audit, CW-20261114-0149).

-- tether_now is strftime('%Y-%m-%dT%H:%M:%fZ','now'): UTC text, millisecond precision, fixed per statement.
-- +goose StatementBegin
CREATE FUNCTION tether_now() RETURNS text LANGUAGE sql STABLE AS $$
    SELECT to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;
-- +goose StatementEnd

-- tether_json parses JSON held as text or as bytea (the team tables' BLOB columns). Malformed JSON raises,
-- as json_extract does. The bytea form is declared IMMUTABLE so expression indexes can use it; that holds
-- because a database's encoding never changes.
-- +goose StatementBegin
CREATE FUNCTION tether_json(text) RETURNS jsonb LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT $1::jsonb
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION tether_json(bytea) RETURNS jsonb LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT convert_from($1, 'UTF8')::jsonb
$$;
-- +goose StatementEnd

-- tether_jx is json_extract: the value at a path, with JSON null read as SQL NULL.
-- +goose StatementBegin
CREATE FUNCTION tether_jx(doc jsonb, path text[]) RETURNS jsonb LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT NULLIF(doc #> path, 'null'::jsonb)
$$;
-- +goose StatementEnd

-- tether_reparse is the inner call of json_extract(json_extract(x, '$.a'), '$.b'): a JSON string holding
-- JSON is parsed again; any other value is used as it is.
-- +goose StatementBegin
CREATE FUNCTION tether_reparse(j jsonb) RETURNS jsonb LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT CASE WHEN jsonb_typeof(j) = 'string' THEN (j #>> '{}')::jsonb ELSE j END
$$;
-- +goose StatementEnd

-- tether_each is json_each's value column: array elements, object values, or a scalar as one row.
-- +goose StatementBegin
CREATE FUNCTION tether_each(j jsonb) RETURNS SETOF jsonb LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF j IS NULL THEN
        RETURN;
    ELSIF jsonb_typeof(j) = 'array' THEN
        RETURN QUERY SELECT jsonb_array_elements(j);
    ELSIF jsonb_typeof(j) = 'object' THEN
        RETURN QUERY SELECT value FROM jsonb_each(j);
    ELSE
        RETURN NEXT j;
    END IF;
END $$;
-- +goose StatementEnd

-- tether_ts stands in for julianday() in comparisons: text without a zone is UTC, 'now' is the statement
-- time, and text that does not parse is NULL.
-- +goose StatementBegin
CREATE FUNCTION tether_ts(t text) RETURNS timestamptz LANGUAGE plpgsql STABLE SET TimeZone = 'UTC' AS $$
BEGIN
    IF t = 'now' THEN
        RETURN statement_timestamp();
    END IF;
    RETURN t::timestamptz;
EXCEPTION WHEN others THEN
    RETURN NULL;
END $$;
-- +goose StatementEnd

-- tether_abort is RAISE(ABORT, msg) for a trigger with no condition.
-- +goose StatementBegin
CREATE FUNCTION tether_abort() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0];
END $$;
-- +goose StatementEnd

-- tether_abort_if_replaced(row, column, msg) is the replaced-session guard most replacement triggers share:
-- abort with msg when the session id in OLD or NEW names the source of a replacement.
-- +goose StatementBegin
CREATE FUNCTION tether_abort_if_replaced() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    r jsonb := CASE TG_ARGV[0] WHEN 'NEW' THEN to_jsonb(NEW) ELSE to_jsonb(OLD) END;
BEGIN
    IF EXISTS (SELECT 1 FROM session_replacements WHERE source_session_id = r ->> TG_ARGV[1]) THEN
        RAISE EXCEPTION '%', TG_ARGV[2];
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END $$;
-- +goose StatementEnd

