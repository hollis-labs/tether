-- message_events_*: one function for the seven SQLite triggers, with the transition as its argument.
-- NOT LIKE becomes NOT ILIKE: SQLite's LIKE folds ASCII case, and ILIKE under COLLATE "C" folds ASCII only.
-- The journal's payload_json becomes the emitted event's payload, so it is built as text, byte for byte
-- what SQLite's json_object writes: compact, keys in call order, strings quoted by to_json (the same
-- escapes as json_quote). TestTriggerParity compares the bytes.
-- +goose StatementBegin
CREATE FUNCTION message_events_fn() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    m    messages;
    at   text;
    meta jsonb;
BEGIN
    IF TG_ARGV[0] = 'purged' THEN
        m := OLD;
        at := tether_now();
    ELSE
        m := NEW;
        at := CASE TG_ARGV[0]
            WHEN 'sent' THEN NEW.created_at
            WHEN 'delivered' THEN NEW.delivered_at
            WHEN 'read' THEN NEW.read_at
            WHEN 'consumed' THEN NEW.consumed_at
            WHEN 'archived' THEN NEW.archived_at
            WHEN 'canceled' THEN NEW.canceled_at
        END;
    END IF;
    IF pg_input_is_valid(m.metadata, 'jsonb') THEN
        meta := m.metadata::jsonb;
    END IF;
    INSERT INTO message_event_journal (kind, at, payload_json, team_run_id)
    VALUES ('message.' || TG_ARGV[0], at,
        '{"message_id":' || to_json(m.id)::text
        || ',"from":' || to_json(m.from_urn)::text
        || ',"to":[' || to_json(m.to_urn)::text || ']'
        || ',"thread_id":' || to_json(coalesce(m.thread_id, ''))::text
        || ',"in_reply_to":' || to_json(coalesce(m.in_reply_to, ''))::text
        || ',"msg_kind":' || to_json(m.kind)::text
        || ',"body_ref":' || to_json('/messages/' || m.id)::text
        || ',"body_bytes":' || octet_length(coalesce(m.payload, ''))
        || ',"content_type":' || to_json(coalesce(m.content_type, ''))::text
        || ',"urgency":' || to_json(CASE WHEN tether_jx(meta, '{urgency}') #>> '{}' IN ('very-low', 'low', 'normal', 'high')
                                         THEN tether_jx(meta, '{urgency}') #>> '{}' ELSE '' END)::text
        || ',"delivery":{"state":' || to_json(TG_ARGV[0])::text
        || ',"delivery_id":' || to_json(coalesce(m.delivery_id, ''))::text || '}}',
        coalesce((SELECT run_id FROM team_runs WHERE run_id = tether_jx(meta, '{team_run}') #>> '{}'), ''));
    RETURN NULL;
END $$;
-- +goose StatementEnd

