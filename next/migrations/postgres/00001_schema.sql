CREATE FUNCTION message_events_group_read_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO message_event_journal (kind, at, payload_json)
    SELECT 'message.read', tether_now(),
        '{"message_id":' || to_json(id)::text
        || ',"from":' || to_json(from_urn)::text
        || ',"to":[' || to_json(NEW.member_urn)::text || ']'
        || ',"thread_id":' || to_json(coalesce(thread_id, ''))::text
        || ',"msg_kind":' || to_json(kind)::text
        || ',"group":' || to_json(group_urn)::text
        || ',"group_seq":' || group_seq
        || ',"body_ref":' || to_json('/groups/' || group_urn || '/messages?message_id=' || id)::text
        || ',"body_bytes":' || octet_length(coalesce(payload, ''))
        || ',"content_type":' || to_json(coalesce(content_type, ''))::text
        || ',"delivery":{"state":"read"}}' 
    FROM messages
    WHERE group_urn = NEW.grp_urn AND group_seq > OLD.last_read_seq AND group_seq <= NEW.last_read_seq AND kind NOT ILIKE 'stream.%';
    RETURN NULL;
