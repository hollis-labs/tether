// exclusion is a source table a final run does not copy, with why. Only these reasons are allowed (cell
// lead's ruling on #601); any other exclusion needs the lead's approval.
type exclusion struct {
	reason string
	plan   string // the plan section that justifies it
}

// exclusions lists every source table migrate-from does not copy. A final run refuses to mark the target
// complete while any source table is neither in a family nor here.
var exclusions = map[string]exclusion{
	// D3: the LLM gateway is out of scope; its audit is archived to llm-archive.db, not loaded.
	"ai_events": {reason: "LLM gateway audit, archived separately (llm-archive.db)", plan: "§7.1 archive, D3"},
	// The old migrator's ledger; the new database keeps goose's version table instead.
	"schema_migrations": {reason: "the old migrator's version ledger, replaced by goose_db_version", plan: "§7 (schema_migrations is kept in the archive as provenance)"},
	// SQLite internals the engine handles itself.
	"sqlite_sequence": {reason: "AUTOINCREMENT marks, carried explicitly per copied table and verified", plan: "§7.2 row identity"},
	"sqlite_stat1":    {reason: "query planner statistics, regenerated by ANALYZE", plan: "§7.2"},
	"sqlite_stat4":    {reason: "query planner statistics, regenerated by ANALYZE", plan: "§7.2"},
	// The forum search index is rebuilt from forum_posts, never copied (FTS5 and its shadow tables).
	"forum_post_fts":         {reason: "forum search index, rebuilt from forum_posts", plan: "§7 (FTS rebuilt and verified by a search per forum), §13.1"},
	"forum_post_fts_data":    {reason: "FTS5 shadow table of forum_post_fts", plan: "§7, §13.1"},
	"forum_post_fts_idx":     {reason: "FTS5 shadow table of forum_post_fts", plan: "§7, §13.1"},
	"forum_post_fts_content": {reason: "FTS5 shadow table of forum_post_fts", plan: "§7, §13.1"},
	"forum_post_fts_docsize": {reason: "FTS5 shadow table of forum_post_fts", plan: "§7, §13.1"},
	"forum_post_fts_config":  {reason: "FTS5 shadow table of forum_post_fts", plan: "§7, §13.1"},
}

// sourceTables lists every table in the source.
func (e *Engine) sourceTables(ctx context.Context) ([]string, error) {
	rows, err := e.src.QueryContext(ctx, `SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name`)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []string
	for rows.Next() {
		var n string
		if err := rows.Scan(&n); err != nil {
			return nil, err
		}
		out = append(out, n)
	}
	return out, rows.Err()
}

// uncovered returns the source tables that are neither in the run nor excluded, sorted.
func (e *Engine) uncovered(ctx context.Context, tables []string) ([]string, error) {
	all, err := e.sourceTables(ctx)
	if err != nil {
		return nil, err
	}
	in := map[string]bool{}
	for _, t := range tables {
		in[t] = true
	}
	var out []string
	for _, t := range all {
		if _, ok := exclusions[t]; !ok && !in[t] {
			out = append(out, t)
		}
	}
	sort.Strings(out)
	return out, nil
}

func joinTables(ts []string) string { return strings.Join(ts, ", ") }

// Covers reports whether migrate-from accounts for a source table: it is in a family or on the exclusion
// list. A final run needs every source table covered.
func Covers(table string) bool {
	if _, ok := exclusions[table]; ok {
		return true
	}
	for _, t := range Families["all"] {
		if t == table {
			return true
		}
	}
	return false
}
